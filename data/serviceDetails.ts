const getImages = (item: any, targetCategory: Category): string[] => {
  if (serviceImages[item.id]) return serviceImages[item.id];
  const routeId = item.route?.replace("/service/", "");
  if (routeId && serviceImages[routeId]) return serviceImages[routeId];
  if (targetCategory === "SaloonWomen") return ["https://images.unsplash.com/photo-1487412720507-e7ab37603c6f"];
  return (categoryImages[targetCategory as keyof typeof categoryImages] || defaultImages);
};

const autoGeneratedDetails: Record<string, ServiceDetail> = combinedAllSubServices.reduce((acc, item) => {
  if (!item || !item.id) return acc;

  const lowerId = item.id.toLowerCase();
  const lowerTitle = (item.title || "").toLowerCase();
  let inferredCategory: Category = "General";
  
  if (lowerId.startsWith("women_") || lowerTitle.includes("women") || lowerTitle.includes("threading") || lowerTitle.includes("facial") || lowerTitle.includes("waxing")) {
    inferredCategory = "SaloonWomen";
  } else if (lowerId.startsWith("men_") || lowerTitle.includes("men salon")) {
    inferredCategory = "SaloonMen";
  } else if (lowerId.startsWith("pest_")) {
    inferredCategory = "PestControl";
  } else if (lowerId.startsWith("paint_")) {
    inferredCategory = "Painting";
  } else if (lowerId.startsWith("clean_") || lowerId.startsWith("maid_")) {
    inferredCategory = "Cleaning";
  } else if (lowerId.startsWith("install_")) {
    inferredCategory = "Installation";
  } else if (lowerId.includes("plumb") || lowerTitle.includes("plumber")) {
    inferredCategory = "Plumbing";
  } else if (lowerId.includes("carpenter") || lowerTitle.includes("carpenter")) {
    inferredCategory = "Carpenter";
  } else if (lowerId.includes("appliance") || lowerTitle.includes("ac repair")) {
    inferredCategory = "Appliance";
  } else if (lowerId.includes("electric") || lowerTitle.includes("electrician")) {
    inferredCategory = "Electrical";
  }

  const targetCategory = item.category || inferredCategory;
  const isSalonType = targetCategory === "SaloonWomen" || targetCategory === "SaloonMen";

  acc[item.id] = {
    id: item.id,
    title: item.title || "Expert Service",
    hindiTitle: item.hindiTitle || "",
    category: targetCategory as any,
    visitCharge: isSalonType ? 0 : 49,
    labourFree: true,
    membershipRequired: !isSalonType,
    materialExtra: !isSalonType,
    description: item.description ?? `Professional ${item.title || "expert"} service.`,
    includes: Array.isArray(item.includes) ? item.includes : ["Premium Service Execution"],
    technician: item.technician || defaultTechnician,
    faqs: item.faqs || defaultFaqs,
    images: Array.isArray(item.images) && item.images.length > 0 ? item.images : getImages(item, targetCategory),
    variants: Array.isArray(item.variants) ? item.variants : [],
    benefits: Array.isArray(item.benefits) ? item.benefits : [],
    brandsUsed: Array.isArray(item.brandsUsed) ? item.brandsUsed : [],
  };

  return acc;
}, {} as Record<string, ServiceDetail>);

export const serviceDetails: Record<string, ServiceDetail> = {
  ...baseParentCategories,
  ...autoGeneratedDetails,
};

export const getServiceById = (id: string): ServiceDetail | undefined => {
  return serviceDetails[id];
};

export default serviceDetails;