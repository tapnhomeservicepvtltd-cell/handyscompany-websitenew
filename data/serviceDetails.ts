const getModuleArrayData = (mod: any): any[] => {
  if (!mod) return [];
  if (Array.isArray(mod.default)) return mod.default;
  const foundArray = Object.values(mod).find((val) => Array.isArray(val));
  return Array.isArray(foundArray) ? foundArray : [];
};

const getFlatWomenSalonServices = (): any[] => {
  // ✅ FIX: womenSalonServices अब पहले से ही एक flat ServiceItem[] array है
  // (पुराना कोड block.subCategories[].services[] जैसे nested structure की उम्मीद कर रहा था,
  // जो अब मौजूद नहीं है — इसी वजह से Women's Salon का डेटा कभी serviceDetails में नहीं आता था)
  if (!Array.isArray(womenSalonServices)) return [];
  // हर item का असली category "threading"/"waxing"/"facial" जैसा sub-type होता है,
  // जो /category/women-salon राउट से मैच नहीं करता — इसलिए यहाँ सिर्फ़ राउटिंग के लिए override करते हैं
  return womenSalonServices.map((item: any) => ({ ...item, category: "women-salon" }));
};

